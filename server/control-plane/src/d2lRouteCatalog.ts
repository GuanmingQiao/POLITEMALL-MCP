import { z } from "zod";

// Single source of truth for every D2L Valence route this server knows how to call.
// Populated from openspec/changes/add-d2l-route-catalog/specs/d2l-route-catalog/catalog.md —
// that file documents the research (path/query params, response envelope, doc source,
// confidence) behind every entry below; keep the two in sync when either changes.
//
// `pathTemplate` always includes `{orgUnitId}` literally for course-scoped routes, but
// `pathParams` never does — orgUnitId is resolved from the caller's courseId, never accepted
// as a direct parameter (see resolveD2lPath in d2l.ts and Decision 3 in design.md). Every other
// `{placeholder}` in pathTemplate must have a matching key in pathParams.

export type D2lProduct = "le" | "lp";
export type D2lScope = "course" | "user" | "global";
// "binary" routes return raw file bytes, not JSON — callers must not attempt to parse the body.
export type D2lPagination = "none" | "objectList" | "bookmark" | "binary";

export interface D2lRouteDescriptor {
  operation: string;
  product: D2lProduct;
  method: "GET";
  pathTemplate: string;
  scope: D2lScope;
  pathParams: z.ZodObject<z.ZodRawShape>;
  queryParams?: z.ZodObject<z.ZodRawShape>;
  pagination: D2lPagination;
  category: string;
  description: string;
  // Most rows back at most one curated tool; a couple (le.quizzes.attempts,
  // le.surveys.attempts) back two — the existing own-scoped tool and the new
  // class-wide one, both hitting the same underlying route.
  curatedTools?: string[];
}

// --- shared param fragments -------------------------------------------------

