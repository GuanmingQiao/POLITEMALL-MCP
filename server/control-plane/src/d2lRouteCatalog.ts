const orgUnitIdsCsvQuery = (extra?: z.ZodRawShape) =>
  z.object({ orgUnitIdsCSV: z.string(), ...(extra ?? {}) });

function route(entry: D2lRouteDescriptor): D2lRouteDescriptor {
  return entry;
}

